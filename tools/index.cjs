// node tools/index.cjs > runs/INDEX.md: one table row per run in runs/, from its report.json, brief and timing.
const fs = require("fs"), p = require("path");
const root = p.join(__dirname, "..", "runs");
const mmss = (s) => `${Math.floor(s / 3600)}:${String(Math.floor((s % 3600) / 60)).padStart(2, "0")}`;
const rows = [];
for (const d of fs.readdirSync(root).sort()) {
  const f = p.join(root, d, "report.json");
  if (!fs.existsSync(f)) continue;
  const r = JSON.parse(fs.readFileSync(f, "utf8"));
  const a = r.agent || {};
  const has = (x) => fs.existsSync(p.join(root, d, x));
  const open = Object.values(r.unconnected || {}).reduce((x, y) => x + y, 0);
  const drc = Object.values(r.drcErrors || {}).reduce((x, y) => x + y, 0);
  const kind = has("keep.txt") ? "place + route" : "route only";
  const exit = has("exit.txt") ? fs.readFileSync(p.join(root, d, "exit.txt"), "utf8").trim() : "";
  rows.push(`| [${d}](${d}/SUMMARY.md) | ${kind} | ${a.model || "?"} | ${r.seconds ? mmss(r.seconds) : "?"} | ${a.costUsd != null ? "$" + a.costUsd.toFixed(2) : "n/a"} | ${drc} | ${open} | ${r.totalVias ?? "?"} | ${[has("work/NOTES.md") && "NOTES", has("work/BT-REVIEW.md") && "BT-REVIEW", has("work/progress") && "progress", has("ask/ANSWER.md") && "ask"].filter(Boolean).join(", ")} | ${exit} |`);
}
console.log(`# Runs

Generated by \`node tools/index.cjs\` from each run's report.json. DRC errors and open (unconnected) items are
KiCad 10 DRC with zones refilled, on the board the agent saved; some boards start with errors of their own
(see the run's drc.json and the board notes in boards/README.md). Cost is what Claude Code reported at API prices
(n/a: the run was stopped by the time limit before Claude Code wrote its result).

| run | task | model | time | cost | DRC errors | open | vias | agent's own files | exit |
|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}`);
